//go:build ignore

// gen_float.go generates the trailing-float fixed-arity syscall variants.
//
// It emits two files:
//
//	syscall_float.go    — Syscall0Float64x1 .. Syscall15Float64x1 (C double)
//	syscall_float32.go  — Syscall0Float32x1 .. Syscall15Float32x1 (C float)
//
// Each family calls a C function that takes N integer (or pointer) arguments
// and exactly one trailing floating-point argument. Run with:
//
//	go run gen_float.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

const maxArity = 15

type variant struct {
	width  int    // 32 or 64
	file   string // output file
	goType string // float32 or float64
	bitsFn string // math.Float32bits or math.Float64bits
	cType  string // "float" or "double" (for docs)
	famDoc string // package-level family doc
}

func main() {
	variants := []variant{
		{
			width:  64,
			file:   "syscall_float.go",
			goType: "float64",
			bitsFn: "math.Float64bits",
			cType:  "double",
			famDoc: float64FamilyDoc,
		},
		{
			width:  32,
			file:   "syscall_float32.go",
			goType: "float32",
			bitsFn: "math.Float32bits",
			cType:  "float",
			famDoc: float32FamilyDoc,
		},
	}

	for _, v := range variants {
		src := generate(v)
		formatted, err := format.Source(src)
		if err != nil {
			fmt.Fprintf(os.Stderr, "format %s: %v\n%s", v.file, err, src)
			os.Exit(1)
		}
		if err := os.WriteFile(v.file, formatted, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "write %s: %v\n", v.file, err)
			os.Exit(1)
		}
		fmt.Printf("wrote %s (%d funcs)\n", v.file, maxArity+1)
	}
}

func generate(v variant) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString(v.famDoc)
	for n := 0; n <= maxArity; n++ {
		writeFunc(&b, v, n)
	}
	return b.Bytes()
}

// writeFunc emits one Syscall<n>Float<width>x1 function.
func writeFunc(b *bytes.Buffer, v variant, n int) {
	name := fmt.Sprintf("Syscall%dFloat%dx1", n, v.width)

	// integer parameter list: a1, a2, ... aN
	ints := make([]string, n)
	for i := range ints {
		ints[i] = fmt.Sprintf("a%d", i+1)
	}

	// function signature
	var sig strings.Builder
	sig.WriteString("fn")
	for _, a := range ints {
		sig.WriteString(", " + a)
	}
	sig.WriteString(" uintptr, f1 " + v.goType)

	// Windows fallback argument list
	var winArgs strings.Builder
	winArgs.WriteString("fn")
	for _, a := range ints {
		winArgs.WriteString(", " + a)
	}
	winArgs.WriteString(", uintptr(" + v.bitsFn + "(f1))")

	// integer-slice assignment
	var assign string
	if n > 0 {
		lhs := make([]string, n)
		for i := range lhs {
			lhs[i] = fmt.Sprintf("tmp[%d]", i)
		}
		assign = strings.Join(lhs, ", ") + " = " + strings.Join(ints, ", ")
	}

	// doc comment
	intDesc := pluralizeInts(n)
	fmt.Fprintf(b, "\n// %s calls fn with %s and one trailing %s.\n", name, intDesc, v.cType)
	fmt.Fprintf(b, "// See the Syscall<N>Float%dx1 family documentation for details and caveats.\n", v.width)
	b.WriteString("//\n//go:uintptrescapes\n")
	fmt.Fprintf(b, "func %s(%s) (r1, r2, err uintptr) {\n", name, sig.String())
	b.WriteString("\tif fn == 0 {\n\t\tpanic(\"purego: fn is nil\")\n\t}\n")
	fmt.Fprintf(b, "\tif runtime.GOOS == \"windows\" {\n\t\treturn syscall_syscallN(%s)\n\t}\n", winArgs.String())
	b.WriteString("\tvar tmp [maxArgs]uintptr\n")
	if assign != "" {
		b.WriteString("\t" + assign + "\n")
	}
	b.WriteString("\tvar floats [maxArgs]uintptr\n")
	fmt.Fprintf(b, "\tfloats[0] = uintptr(%s(f1))\n", v.bitsFn)
	b.WriteString("\ts := syscall_SyscallN(fn, tmp[:], floats[:], 0)\n")
	b.WriteString("\tdefer thePool.Put(s)\n")
	b.WriteString("\treturn s.a1, s.a2, s.a3\n}\n")
}

func pluralizeInts(n int) string {
	switch n {
	case 0:
		return "no integer arguments"
	case 1:
		return "one integer argument"
	default:
		return fmt.Sprintf("%s integer arguments", numberWord(n))
	}
}

func numberWord(n int) string {
	words := []string{"zero", "one", "two", "three", "four", "five", "six", "seven",
		"eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen"}
	if n < len(words) {
		return words[n]
	}
	return fmt.Sprintf("%d", n)
}

