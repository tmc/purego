const float64FamilyDoc = `
// The Syscall<N>Float64x1 family is a set of fixed-arity variants of [SyscallN]
// for calling C functions that take N integer (or pointer) arguments and
// exactly one trailing double argument. Unlike [SyscallN], which cannot
// correctly call functions that mix integer and floating-point parameters,
// these variants place the integer arguments and the float argument in their
// respective register classes, matching the platform C ABI.
//
// The integer arguments a1..aN are passed in the integer argument registers in
// order; f1 is passed as a double in the first floating-point argument
// register. This is correct on platforms whose C ABI assigns integer and
// floating-point arguments to independent register files (such as the
// AArch64 AAPCS and the AMD64 System V ABI), regardless of where the float
// appears in the C declaration relative to the integer arguments. For
// example, a C function declared as
//
//	long f(long a, long b, double x, long c)
//
// is called as Syscall3Float64x1(fn, a, b, c, x): the three integer arguments
// are passed positionally and x is passed as the trailing double.
//
// The x1 suffix denotes a single trailing floating-point argument. Only this
// shape — N integers and exactly one trailing double — is provided. Multiple
// floating-point arguments, or more than eight floating-point arguments that
// would spill onto the stack, are not expressible through this family and are
// intentionally omitted; use [RegisterFunc] for those.
//
// On Windows the underlying helper cannot place a value in a floating-point
// register, so these variants fall back to passing the raw bits of f1 as an
// additional integer argument; they are correct only on platforms that use the
// purego funnel (see [SyscallN]).
`

const float32FamilyDoc = `
// The Syscall<N>Float32x1 family is the single-precision counterpart of the
// [Syscall0Float64x1] family. Each variant calls a C function that takes N
// integer (or pointer) arguments and exactly one trailing float (float32)
// argument.
//
// The integer arguments a1..aN are passed in the integer argument registers in
// order; f1 is passed as a single-precision float in the first floating-point
// argument register. On platforms whose C ABI assigns integer and
// floating-point arguments to independent register files (the AArch64 AAPCS and
// the AMD64 System V ABI), a float argument occupies the low 32 bits of the
// first floating-point register, so the float bits are written there directly;
// this is correct regardless of where the float appears in the C declaration
// relative to the integer arguments.
//
// The Syscall<N>Float32x1 and [Syscall0Float64x1] families are not
// interchangeable: a float bit pattern read by a double parameter (or the
// reverse) yields a different value. Match the family to whether the C function
// declares its scalar parameter as float or double.
//
// The x1 suffix denotes a single trailing floating-point argument. The same
// restrictions as the double family apply: only the shape of N integers and
// exactly one trailing float is provided; multiple floating-point arguments, or
// arguments that spill onto the stack, are not expressible and are intentionally
// omitted; use [RegisterFunc] for those.
//
// On Windows the underlying helper cannot place a value in a floating-point
// register, so these variants fall back to passing the raw bits of f1 as an
// additional integer argument; they are correct only on platforms that use the
// purego funnel (see [SyscallN]).
`
